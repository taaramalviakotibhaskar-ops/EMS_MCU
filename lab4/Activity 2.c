/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART2_UART_Init();
  MX_ADC1_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);
  // Start listening for 1 byte via interrupt
  HAL_UART_Receive_IT(&huart2, (uint8_t *)rxBuffer, 1);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
    HAL_ADC_Start(&hadc1);

    while (1)
    {
        // 1. Read ADC and update Servo
        if (HAL_ADC_PollForConversion(&hadc1, 10) == HAL_OK)
        {
            adcValue = HAL_ADC_GetValue(&hadc1);
            uint32_t servo_pos = 10 + (adcValue * 10) / 4095;
            __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, servo_pos);
        }

        // 2. Append the newest reading to txBuffer (DO NOT SEND YET)
        // We use sprintf to write directly to the end of the existing string
        // Safety check: Only append if we have enough space in the 512-byte buffer!
        if (bufferLength < 400) {
            bufferLength += sprintf((char *)&txBuffer[bufferLength],
                                    "%lu. AUT2026 EMS SID: 25916329, ADC Reading: %lu\r\n",
                                    messageCount, adcValue);
            messageCount++;
        }

        // 3. Check if 'J' was pressed (Interrupt flag)
        if (jKeyPressed == 1) {
            // Send the entire backlog using the Interrupt-based transmit function
            HAL_UART_Transmit_IT(&huart2, (uint8_t *)txBuffer, bufferLength);

            // Reset our trackers so the buffer starts filling from the beginning again
            bufferLength = 0;
            jKeyPressed = 0;
        }

        // 4. Blink the LED with delay (This represents our main loop workload)
        HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_5);
        // The lab mentions appending once per second. Two 500ms delays (or toggles) makes 1 second,
        // but 500ms delay per loop is usually accepted.
        HAL_Delay(500);

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

